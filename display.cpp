// Status display for LilyGO T-Dongle-S3 style boards (ST7735 0.96" 160x80 IPS)
// Minimal dependency-free driver: no external library needed.
// Shows IP, status, blocked/allowed counters, blocklist size, RSSI, uptime, free memory.

