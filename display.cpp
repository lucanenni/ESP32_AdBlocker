// pins of the GNPE 'Pocket-Dongle-S3' clone (from lucanenni/spark-go-utils, ESP32-S3-ChocolatePlus-bridge)
#define TFT_MOSI 11
#define TFT_SCLK 10
#define TFT_CS   12
#define TFT_DC   13
#define TFT_RST  14
#define TFT_BL   -1          // backlight is hardwired on, no GPIO
#define BL_ACTIVE_LOW false

#define TFT_W 160
#define TFT_H 80
// panel offsets for 0.96" 80x160 ST7735S in landscape
#define X_OFF 0
#define Y_OFF 24
// MADCTL: 0xA0 = landscape; try 0x60 if the picture is upside down
#define TFT_MADCTL 0xA8 // MY|MV|BGR (panel is BGR); 0x68 if upside down

#define C_BLACK  0x0000
#define C_WHITE  0xFFFF
#define C_GREEN  0x07E0
#define C_RED    0xF800
#define C_YELLOW 0xFFE0
#define C_CYAN   0x07FF
#define C_GREY   0x8410

static SPIClass tftSPI(HSPI);
static const SPISettings tftSet(27000000, MSBFIRST, SPI_MODE0);

